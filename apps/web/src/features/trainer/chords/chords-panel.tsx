import { canShowTab, type Track } from '@reprise/model';
import { useEffect, useMemo, useRef, useState, type KeyboardEvent } from 'react';
import { useStore } from 'zustand';

import { useAppServices } from '@/app/services-context';
import { Button } from '@/components/ui/button';
import { Input } from '@/components/ui/input';
import { Switch } from '@/components/ui/switch';
import { useCommand } from '@/app/use-command';
import { useSetting } from '@/app/use-setting';
import { CHORD_STRIP_SETTING } from '@/state/app-settings';
import { chordNamesIn, commitEdit } from '@/features/editor';
import { parseChord, voicings } from '@/lib/chords';

import { tuningNames } from '../fretboard/fretboard-model';

import { boxOf, ChordCard, PAD } from './chord-card';
import { chordNameAtPlayhead, chordNameOfBeat } from './chord-target';
import { strum } from './strum';
import { beatsNamed, shapeOnBeat, shapeOnEveryBeat } from './write-shape';

const MAX_SHAPES = 24;
const SONG_NAMES = 8;
/** The card's own padding and border around the diagram, in px. */
const CARD_CHROME = 14;

function trackLine(track: Track): string {
  const tuning = tuningNames(track).join(' ');
  return track.capo > 0
    ? `${track.name}, ${tuning}, capo ${String(track.capo)}`
    : `${track.name}, ${tuning}`;
}

interface At {
  query: string;
  index: number;
}

/**
 * The Chords tab (#352): shapes for any chord name on the current track's tuning and capo,
 * generated by `lib/chords`. A click strums a shape and picks it; in edit mode the buttons write
 * the picked shape to the cursor's beat or to every beat of that name, each one undo step.
 */
export function ChordsPanel() {
  const services = useAppServices();
  const { ui, document, selection, editing, audio, heard } = services;
  const score = useStore(document, (state) => state.score);
  const currentTrack = useStore(selection, (state) => state.currentTrack);
  const cursorBeat = useStore(selection, (state) => state.cursor?.beat);
  const isEditing = useStore(editing, (state) => state.editing);
  const name = useStore(ui, (state) => state.chordsName);
  const setName = useStore(ui, (state) => state.setChordsName);
  const [picked, setPicked] = useState<At>();
  const [focusAt, setFocusAt] = useState<At>();
  const cancel = useRef<() => void>(undefined);
  const cards = useRef<(HTMLButtonElement | null)[]>([]);
  const toggleStrip = useCommand('view.toggleChordStrip');
  const stripOn = useSetting(CHORD_STRIP_SETTING);

  const track: Track | undefined =
    score && (score.tracks.find((t) => t.id === currentTrack) ?? score.tracks[0]);
  const trackId = track?.id;
  const fretted = track !== undefined && canShowTab(track);
  const query = name.trim();
  const chord = useMemo(() => (query === '' ? undefined : parseChord(query)), [query]);
  const shapes = useMemo(
    () => (track && fretted && chord ? voicings(chord, track, { limit: MAX_SHAPES }) : []),
    // The track's tuning, capo and fret count decide the shapes, not its notes.
    // eslint-disable-next-line react-hooks/exhaustive-deps
    [chord, fretted, track?.tuning, track?.capo, track?.fretCount],
  );
  const box = useMemo(() => boxOf(shapes.map((entry) => entry.diagram)), [shapes]);
  const songNames = useMemo(() => (score ? chordNamesIn(score).slice(0, SONG_NAMES) : []), [score]);
  const last = shapes.length - 1;
  // Both indexes belong to one query and are clamped: a track change can shorten the list.
  const pickedIndex = Math.min(picked?.query === query ? picked.index : 0, Math.max(last, 0));
  const tabIndexAt = Math.min(
    focusAt?.query === query ? focusAt.index : pickedIndex,
    Math.max(last, 0),
  );
  const shape = shapes[pickedIndex];

  const hasScore = score !== undefined;
  // An empty tab opens on something: the cursor's chord, the chord at the playhead, then the song's first.
  useEffect(() => {
    if (!hasScore || ui.getState().chordsName.trim() !== '') return;
    const { score: current } = document.getState();
    const now =
      current &&
      (current.tracks.find((t) => t.id === selection.getState().currentTrack) ?? current.tracks[0]);
    const seeded =
      chordNameOfBeat(services, selection.getState().cursor?.beat) ??
      (current && now ? chordNameAtPlayhead(current, now, heard.current) : undefined) ??
      (current ? chordNamesIn(current)[0] : undefined);
    if (seeded) ui.getState().setChordsName(seeded);
  }, [hasScore, ui, document, selection, heard, services]);

  // A strum belongs to the track it was struck on: another track or song ends it.
  const file = useStore(document, (state) => state.file);
  useEffect(
    () => () => {
      cancel.current?.();
    },
    [trackId, file],
  );

  if (!score || !track) {
    return <p className="text-muted-foreground p-3 text-sm">Open a song to see chord shapes.</p>;
  }

  const play = (index: number) => {
    const entry = shapes[index];
    if (!entry) return;
    setPicked({ query, index });
    cancel.current?.();
    cancel.current = strum(
      audio,
      track,
      entry.diagram,
      () => document.getState().score?.tracks.some((t) => t.id === track.id) === true,
    );
  };

  const columns = () => {
    const top = cards.current[0]?.offsetTop;
    const count = cards.current.filter((card) => card?.offsetTop === top).length;
    return Math.max(count, 1);
  };

  const onKeyDown = (index: number) => (event: KeyboardEvent<HTMLButtonElement>) => {
    const target =
      event.key === 'ArrowRight'
        ? index + 1
        : event.key === 'ArrowLeft'
          ? index - 1
          : event.key === 'ArrowDown'
            ? index + columns()
            : event.key === 'ArrowUp'
              ? index - columns()
              : event.key === 'Home'
                ? 0
                : event.key === 'End'
                  ? last
                  : undefined;
    if (target === undefined) return;
    event.preventDefault();
    cards.current[Math.min(Math.max(target, 0), last)]?.focus();
  };

  const writeCursor = () => {
    if (!shape || cursorBeat === undefined || !query) return;
    commitEdit(services, shapeOnBeat(cursorBeat, query, shape.diagram), { moveCursor: false });
  };
  const sameName = beatsNamed(track, query).length;
  const writeEvery = () => {
    if (!shape) return;
    const command = shapeOnEveryBeat(track, query, shape.diagram);
    if (command) commitEdit(services, command, { moveCursor: false });
  };

  const message = !fretted
    ? ''
    : query !== '' && !chord
      ? 'No shapes for this chord name'
      : chord && shapes.length === 0
        ? `No shapes for ${query} on this track`
        : '';

  return (
    <section
      aria-label="Chord shapes"
      className="flex min-h-0 flex-1 flex-col gap-2 overflow-y-auto p-3"
    >
      <div className="flex flex-col gap-1">
        <label htmlFor="chords-name" className="text-sm font-medium">
          Chord
        </label>
        <Input
          id="chords-name"
          value={name}
          placeholder="Am, G7, Dsus4, F#m7b5"
          autoComplete="off"
          spellCheck={false}
          onChange={(event) => {
            setName(event.target.value);
          }}
        />
        {songNames.length > 0 && (
          <div role="group" aria-label="Chords in this song" className="flex flex-wrap gap-1">
            {songNames.map((songName) => (
              <Button
                key={songName}
                variant="outline"
                size="xs"
                onClick={() => {
                  setName(songName);
                }}
              >
                {songName}
              </Button>
            ))}
          </div>
        )}
      </div>
      <div className="flex items-center justify-between gap-2">
        <label htmlFor="chords-strip" className="text-sm">
          Chord strip above the score
        </label>
        <Switch
          id="chords-strip"
          checked={stripOn}
          onCheckedChange={() => {
            toggleStrip.run();
          }}
        />
      </div>
      <p className="text-muted-foreground text-xs">
        {fretted ? trackLine(track) : 'Chord shapes need a fretted track'}
      </p>
      {fretted && track.capo > 0 && (
        <p className="text-muted-foreground text-xs">
          Names are the chord you hear, and frets count from the capo.
        </p>
      )}
      {/* Always mounted, so a screen reader hears the text change. */}
      <p role="status" className="text-sm">
        {message}
      </p>
      {shapes.length > 0 && (
        <>
          <p className="text-muted-foreground text-xs">Suggested shapes. Click one to hear it.</p>
          <ul
            aria-label={`${query} shapes`}
            className="m-0 grid list-none gap-2 p-0"
            style={{
              gridTemplateColumns: `repeat(auto-fill, minmax(${String(box.width + 2 * PAD + CARD_CHROME)}px, 1fr))`,
            }}
          >
            {shapes.map((entry, index) => (
              <li
                key={entry.diagram.frets.join(',') + String(entry.diagram.baseFret)}
                className="flex"
              >
                <ChordCard
                  name={query}
                  diagram={entry.diagram}
                  box={box}
                  picked={index === pickedIndex}
                  tabIndex={index === tabIndexAt ? 0 : -1}
                  buttonRef={(element) => {
                    cards.current[index] = element;
                  }}
                  onPlay={() => {
                    play(index);
                  }}
                  onFocus={() => {
                    setFocusAt({ query, index });
                  }}
                  onKeyDown={onKeyDown(index)}
                />
              </li>
            ))}
          </ul>
        </>
      )}
      {isEditing && shape && (
        <div className="flex flex-col gap-1.5 border-t pt-2">
          <Button size="sm" disabled={cursorBeat === undefined} onClick={writeCursor}>
            Use this shape
          </Button>
          <Button size="sm" variant="outline" disabled={sameName === 0} onClick={writeEvery}>
            Use for every {query} in this track
          </Button>
        </div>
      )}
    </section>
  );
}
